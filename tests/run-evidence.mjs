// The carried part follows measured failure evidence, including routing gaps and unavailable capacity.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { runEvidence, failureEvidence } from '../ui/play/run-transition.js';
import { createCatalog } from '../sim/catalog.js';
import { createSim } from '../sim/engine.js';
import { problemById } from '../content/problems/index.js';
const catalog = createCatalog(Object.fromEntries(['elements', 'requests', 'events', 'world'].map(k => [k, JSON.parse(fs.readFileSync(`catalog/${k}.json`, 'utf8'))])));
const graph = { nodes: ['client', 'app', 'db'].map(id => ({ id, type: id })), edges: [{ kind: 'flow', from: 'client', to: 'app' }, { kind: 'flow', from: 'app', to: 'db' }] };
const result = { passed: false, graph, firstFailure: { nodeId: 'app', kind: 'dependency', util: null },
  nodes: [{ id: 'client', failed: 100, peakUtil: 0 }, { id: 'app', failed: 10, peakUtil: .2 }], slo: { cost: { perMonth: 1, budget: 10 } } };
assert.equal(runEvidence(result)[0].id, 'app', 'the cause takes precedence over upstream failed-request totals');
assert.deepEqual(runEvidence({ graph: { nodes: [], edges: [] } }), []);
assert.equal(failureEvidence(result, catalog).heading, 'The part to inspect');
assert.match(failureEvidence(result, catalog).detail, /capacity was unavailable/);
assert.equal(failureEvidence({ ...result, firstFailure: { nodeId: 'app', kind: 'capacity', util: 1.2 } }, catalog).heading, 'The part that reached its limit');
assert.equal(failureEvidence({ ...result, firstFailure: null }, catalog).heading, 'The part to inspect', 'failed work without saturation is not capacity exhaustion');
assert.equal(failureEvidence({ ...result, checks: { availability: true, cost: false }, slo: { cost: { perMonth: 20, budget: 10 } } }, catalog).heading, 'The part behind the cost', 'a transient traffic failure does not hide the actual missed SLO');
const shortener = problemById.get('url-shortener');
const sim = createSim({ catalog, problem: shortener, seed: 'practice' });
sim.loadGraph(shortener.editorial.designs[0].graph);
const idle = Array.from({ length: 10 }, (_, i) => sim.addNode('dns', i * 160, 600));
for (let i = 1; i < idle.length; i++) sim.connect(idle[i - 1], idle[i]);
sim.start(); sim.advance(86400000);
assert.equal(sim.result().score.total, 1000);
const traces = Object.keys(shortener.requirements.mix).map(t => sim.trace(t));
const path = runEvidence(sim.result(), { catalog, traces });
assert(path.length >= 3 && path.length <= 5);
assert.equal(catalog.elementById.get(path[0].type).kind, 'source');
assert(path.slice(1).every(n => sim.result().nodes.find(m => m.id === n.id).peakRequests > 0));
assert(path.every(n => !idle.includes(n.id)), 'unused structural chains never replace the measured request route');
assert(traces.some(t => path.every(n => t.nodeIds.includes(n.id))), 'a summary follows one request type');
const large = { nodes: Array.from({ length: 20 }, (_, i) => ({ id: 'n' + i, type: i ? 'dns' : 'web-browser' })), edges: Array.from({ length: 19 }, (_, i) => ({ id: 'e' + i, from: 'n' + i, to: 'n' + (i + 1), kind: 'flow' })) };
assert.equal(runEvidence({ passed: true, graph: large, nodes: large.nodes.map(n => ({ id: n.id, peakRequests: 10 })) }, { catalog, traces: [{ nodeIds: large.nodes.map(n => n.id), edgeIds: large.edges.map(e => e.id) }] }).length, 5, 'the carried path stays small on phones');
const benefits = problemById.get('benefits-portal');
const retention = createSim({ catalog, problem: benefits, seed: 'practice' });
retention.loadGraph(benefits.editorial.designs[0].graph);
const db = retention.getGraph().nodes.find(n => n.type === 'sql-primary');
retention.setKnob(db.id, 'retentionDays', 5);
retention.start(); retention.advance(86400000);
const failed = retention.result();
assert.equal(failed.checks.safety, false);
assert.equal(failed.firstFailure, null);
assert.equal(runEvidence(failed, { catalog })[0].id, db.id, 'retention evidence identifies the authoritative database');
const evidence = failureEvidence(failed, catalog);
assert.equal(evidence.heading, 'The requirement that missed');
assert.match(evidence.detail, /keeps data for 5 days/);
assert.doesNotMatch(evidence.detail, /failed requests|busy/);
assert.doesNotMatch(evidence.detail, /Increase|archival path/, 'carried facts preserve the prediction gate on repair advice');
const otherSafety = failureEvidence({ ...failed, slo: { ...failed.slo, safety: { lostWrites: 4, duplicates: 2, compliance: { failed: ['encryption'] } } } }, catalog);
assert.match(otherSafety.heading, /safety requirement/);
assert.match(otherSafety.detail, /writes lost.*duplicate effects.*compliance/);
console.log('Carried evidence follows the measured cause and bounds large path summaries.');
