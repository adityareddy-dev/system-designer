// Named loads and event durations remain distinct from grading thresholds.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createCatalog } from '../sim/catalog.js';
import { createSim } from '../sim/engine.js';
import { problemById } from '../content/problems/index.js';
import { loadSummary, gradingContract } from '../ui/play/load-labels.js';
import { twistProblem } from '../content/problems/twist.js';
const short = problemById.get('url-shortener');
assert.match(loadSummary({ ...short, warmUp: true, normalPeakRps: 5000, requirements: { ...short.requirements, peakRps: 1250 } }), /Warm-up peak:.*Normal peak:.*5k/);
assert.match(gradingContract(short), /85%.*served interactive requests.*80%/);
assert.doesNotMatch(gradingContract(short), /slow minutes allowed/);
const ticket = problemById.get('concert-ticket-drop');
assert.match(loadSummary(ticket), /600 req\/s.*15k req\/s/);
const transfer = twistProblem(ticket);
assert.equal(transfer.numbers[0].value, 3750);
assert.equal(transfer.numbers[1].value, 2137.5);
assert.match(loadSummary(transfer), /150 req\/s.*3.8k req\/s/);
assert.doesNotMatch(loadSummary(transfer), /holds\/s|sell-out/);
for (const id of ['firmware-rollout', 'flash-sale-inventory']) {
  const scenario = twistProblem(problemById.get(id));
  assert.equal(scenario.numbers[0].value, scenario.requirements.peakRps);
  assert.equal(scenario.numbers[0].label, 'New arrival rate setting', 'a non-crowd event never invents a 25 times crowd peak');
}
assert.match(gradingContract(ticket), /95%.*served interactive requests.*80%/);
const read = name => JSON.parse(fs.readFileSync(new URL('../catalog/' + name + '.json', import.meta.url)));
const catalog = createCatalog({ elements: read('elements'), requests: read('requests'), events: read('events'), world: read('world') });
const arrivals = createSim({ catalog, problem: transfer });
arrivals.start(); arrivals.advance(60000);
assert(Math.abs(arrivals.state().traffic.offeredRps - 150) < 2, 'normal arrivals follow the drop curve, with seeded tick jitter');
const [hour, minute] = transfer.events.find(e => e.id === 'flash-crowd').at.split(':').map(Number);
arrivals.advance((hour * 60 + minute) * 60000);
assert(Math.abs(arrivals.state().traffic.offeredRps / transfer.numbers[0].value - 1) < .02, 'worked total describes the fully ramped event peak');
assert(Math.abs(arrivals.state().traffic.byType.read.offered / transfer.numbers[1].value - 1) < .02, 'worked reads describe the same peak');
const sim = createSim({ catalog, problem: ticket });
sim.loadGraph(ticket.editorial.designs[0].graph);
sim.start(); sim.advance(86400000);
const ev = sim.result().events.find(e => e.id === 'flash-crowd');
assert.equal(ev.durations.spikeSec, 900);
assert.equal(ev.durations.recoverySec, 1800);
assert.equal(ev.durations.rampSec, 30);
assert.ok(ev.durations.overloadSec >= 0 && ev.durations.overloadSec <= ev.durations.observedSec);
assert.ok(ev.durations.observedSec > ev.durations.spikeSec + ev.durations.recoverySec);
console.log('Named load, grading and duration checks passed.');
