// Live edits must not invent outages or reuse measurements from the previous graph.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createCatalog } from '../sim/catalog.js';
import { createSim } from '../sim/engine.js';
import lesson from '../content/lessons/load-balancing.js';
const catalog = createCatalog(Object.fromEntries(['elements','requests','events','world'].map(k => [k, JSON.parse(fs.readFileSync(`catalog/${k}.json`, 'utf8'))])));
const sim = createSim({ catalog, problem: lesson.steps[1].setup, mode: 'lesson' });
sim.start(); sim.advance(600000);
const lb = sim.addNode('regional-lb', 0, 0);
sim.disconnect('users>app'); sim.connect('users', lb); sim.connect(lb, 'app'); sim.setKnob('app', 'units', 5);
let st = sim.state();
assert.equal(st.nodes.find(n => n.id === 'app').availableUnits, 5, 'an edit does not take healthy servers down');
assert.equal(st.traffic.offeredRps, 0, 'the changed graph has not measured traffic yet');
sim.advance(60000);
st = sim.state();
assert.equal(st.traffic.successRps, st.traffic.offeredRps);
assert.equal(st.nodes.find(n => n.id === 'app').availableUnits, 5);
sim.pause(); sim.setKnob('app', 'units', 6);
assert.equal(sim.state().nodes.find(n => n.id === 'app').availableUnits, 6);
assert.equal(sim.state().traffic.offeredRps, 0, 'paused edits cannot claim the last graph passed');
sim.advance(10000);
assert(sim.state().traffic.offeredRps > 0);
const outage = createSim({ catalog, problem: { ...lesson.steps[1].setup, events: [{ id: 'region-outage', at: '00:00', params: { region: 'us' } }] }, mode: 'lesson' });
outage.start(); outage.advance(60000);
assert.equal(outage.state().nodes.find(n => n.id === 'app').availableUnits, 0);
outage.setKnob('app', 'units', 5);
assert.equal(outage.state().nodes.find(n => n.id === 'app').availableUnits, 0, 'an edit must preserve a real ongoing outage');
assert.equal(outage.state().nodes.find(n => n.id === 'app').status, 'down');
assert.equal(outage.flows().nodeStatus[1], 4, 'the drawing agrees with the measured outage');
sim.start();
assert.equal(sim.state().traffic.offeredRps, 0, 'restarting a paused day waits for a new measurement');
sim.advance(10000);
assert(sim.state().traffic.offeredRps > 0);
console.log('Healthy pool availability and fresh measurements survive live and paused edits.');
