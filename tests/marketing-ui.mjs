import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { serveGame } from './browser-server.js';

const site = await serveGame(null);
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const out = path.resolve('.task-tmp/screenshots');
fs.mkdirSync(out, { recursive: true });
try {
  const context = await browser.newContext({ timezoneId: 'Europe/London', viewport: { width: 1280, height: 900 } });
  await context.route(/https:\/\/(?:www\.)?(?:googletagmanager|google-analytics)\.com\//, route => route.fulfill({ body: '', contentType: 'text/javascript' }));
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(site.base + '?preview=hosted#/settings');
  await page.getByRole('heading', { name: 'Privacy and feedback', exact: true }).waitFor();
  assert.match(await page.locator('.sh-settings-card').filter({ has: page.getByRole('heading', { name: 'Privacy and feedback', exact: true }) }).innerText(), /Google Analytics has a separate cookie choice/);
  const banner = page.locator('#sd-cookie-banner');
  await banner.waitFor();
  const consent = () => page.evaluate(() => window.dataLayer.filter(a => a[0] === 'consent').map(a => ({ type: a[1], ...a[2] })));
  assert.equal((await consent())[0].analytics_storage, 'denied');
  await page.screenshot({ animations: 'disabled', path: path.join(out, 'cookie-banner.png') });
  await banner.getByRole('button', { name: 'Decline', exact: true }).click();
  await page.reload();
  assert.equal(await banner.count(), 0);
  assert.equal((await consent())[0].analytics_storage, 'denied');
  await page.getByRole('button', { name: 'Cookie choices', exact: true }).click();
  await banner.getByRole('button', { name: 'Accept', exact: true }).click();
  assert.equal((await consent()).at(-1).analytics_storage, 'granted');
  for (const c of await consent()) for (const field of ['ad_storage', 'ad_user_data', 'ad_personalization']) assert.equal(c[field], 'denied');
  await page.reload();
  assert.equal(await banner.count(), 0);
  assert.equal((await consent())[0].analytics_storage, 'granted');
  await page.getByRole('button', { name: 'Sign in', exact: true }).first().click();
  await page.getByRole('button', { name: /Continue with GitHub/ }).click();
  const panel = page.getByRole('dialog', { name: 'Email updates' });
  await panel.waitFor();
  const box = panel.getByRole('checkbox');
  assert.equal(await box.isChecked(), false, 'unknown country preview starts unticked');
  await page.screenshot({ animations: 'disabled', path: path.join(out, 'first-sign-in.png') });
  await box.check();
  await panel.getByRole('button', { name: 'Save choice', exact: true }).click();
  await panel.waitFor({ state: 'detached' });
  await page.locator('#sh-email-card').waitFor();
  assert.equal(await page.locator('#sh-email-card input[type=checkbox]').isChecked(), true);
  await page.screenshot({ animations: 'disabled', path: path.join(out, 'settings.png') });
  await page.locator('#sh-email-card input[type=checkbox]').uncheck();
  await page.reload();
  await page.locator('#sh-email-card').waitFor();
  assert.equal(await page.locator('#sh-email-card input[type=checkbox]').isChecked(), false);
  assert.equal(await panel.count(), 0, 'saved choices do not prompt again');
  await page.locator('.ac-me-btn').click();
  await page.getByRole('button', { name: 'Delete my account', exact: true }).click();
  const deletion = page.getByRole('dialog', { name: 'Delete your account?' });
  assert.match(await deletion.innerText(), /We keep your email until the unsubscribe is sent/);
  await deletion.getByRole('button', { name: 'Delete my account', exact: true }).click();
  await page.getByText('Account deleted. Progress saved on this device stays here.', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  await context.close();
  const mobile = await browser.newContext({ timezoneId: 'Europe/London', viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const phone = await mobile.newPage();
  await phone.goto(site.base + '?preview=hosted#/settings');
  await phone.locator('#sd-cookie-banner').waitFor();
  await phone.getByRole('button', { name: 'Sign in', exact: true }).first().click();
  await phone.getByRole('button', { name: /Continue with Google/ }).click();
  const phonePrompt = phone.getByRole('dialog', { name: 'Email updates' });
  await phonePrompt.waitFor();
  await phone.screenshot({ animations: 'disabled', path: path.join(out, 'first-sign-in-mobile.png') });
  assert.equal(await phonePrompt.getByRole('button', { name: 'Save choice' }).evaluate(button => {
    const rect = button.getBoundingClientRect();
    return document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)?.closest('button') === button;
  }), true, 'the cookie banner does not cover the save button');
  await phonePrompt.getByRole('button', { name: 'Save choice' }).click();
  await phonePrompt.waitFor({ state: 'detached' });
  await phone.screenshot({ animations: 'disabled', path: path.join(out, 'cookie-banner-mobile.png') });
  await mobile.close();
  console.log('First-sign-in choice, Settings, cookie choices and screenshots passed.');
} finally { await browser.close(); await site.close(); }
