// Checks that lesson capacity guidance follows the engine and diagnoses queue limits.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createCatalog } from '../sim/catalog.js';
import { createSim } from '../sim/engine.js';
import { queueDrainAdvice } from '../ui/play/lesson-queue.js';
import loadBalancing from '../content/lessons/load-balancing.js';
import replication from '../content/lessons/replication-lag.js';
import queues from '../content/lessons/queues-backpressure.js';
const read = file => JSON.parse(fs.readFileSync(new URL(`../catalog/${file}.json`, import.meta.url)));
const catalog = createCatalog({ elements: read('elements'), requests: read('requests'), events: read('events'), world: read('world') });
const demo = lesson => createSim({ catalog, problem: { id: lesson.id, ...lesson.steps[1].setup }, mode: 'lesson', seed: 'lesson-guidance' });
const lb = demo(loadBalancing);
lb.setKnob('app', 'units', 5);
const balancer = lb.addNode('regional-lb', -400, 0);
lb.disconnect(lb.getGraph().edges.find(e => e.from === 'users' && e.to === 'app').id);
lb.connect('users', balancer); lb.connect(balancer, 'app');
lb.start(); lb.advance(12 * 3600000);
let st = lb.state();
assert.ok(st.traffic.offeredRps > 2900 && st.traffic.offeredRps < 3100, 'demo peak agrees with 3,000/s caption');
assert.ok(st.traffic.successRps / st.traffic.offeredRps >= .99);
assert.ok(st.nodes.find(n => n.id === 'app').util < .7, 'five servers leave the stated headroom');
const rep = demo(replication);
const replica = rep.addNode('sql-replica', 0, 100, { units: 4 });
rep.connect('db', replica); rep.connect('app', replica);
rep.start(); rep.advance(12 * 3600000);
assert.ok(rep.state().nodes.find(n => n.id === 'db').util < .7, 'guided wiring and sizing meet the primary goal');
const q = demo(queues);
q.disconnect(q.getGraph().edges.find(e => e.from === 'app' && e.to === 'db').id);
const queue = q.addNode('queue', -200, 0), workers = q.addNode('worker-pool', -100, 0, { units: 30 });
q.connect('app', queue); q.connect(queue, workers); q.connect(workers, 'db');
q.start(); q.advance(12.2 * 3600000);
let advice = queueDrainAdvice(q.getGraph(), q.state(), catalog, { write: 1 });
assert.match(advice, /SQL database limits downstream service to ≈ 2,000/);
assert.match(advice, /More workers cannot raise that limit/);
assert.match(advice, /Arrivals are/);
q.setKnob(workers, 'units', 1);
advice = queueDrainAdvice(q.getGraph(), q.state(), catalog, { write: 1 });
assert.match(advice, /Increase worker units/);
q.setKnob(workers, 'units', 30);
const state = structuredClone(q.state());
Object.assign(state.nodes.find(n => n.id === queue), { queueAcceptedRps: 1500, queueDrainRps: 2000, queueDepth: 1000000 });
advice = queueDrainAdvice(q.getGraph(), state, catalog, { write: 1 });
assert.match(advice, /shrinking by ≈ 500\/s/);
assert.match(advice, /≈ 33 minutes remain/);
console.log('Lesson guidance checks passed.');
