// Identical defense experiments share a day, while edits and predictions remain independent.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { registerHooks } from 'node:module';
import { createCatalog } from '../sim/catalog.js';
import { problemById } from '../content/problems/index.js';

globalThis.__claimReplayDays = 0;
const hook = registerHooks({ load(url, context, nextLoad) {
  const loaded = nextLoad(url, context);
  if (!url.endsWith('/sim/engine.js')) return loaded;
  const source = String(loaded.source);
  assert(source.includes('advance(simMs) {'));
  return { ...loaded, source: source.replace('advance(simMs) {', 'advance(simMs) { if (simMs === 86400000) globalThis.__claimReplayDays++;') };
} });
const { createSim } = await import('../sim/engine.js');
const { claimsFor, checkClaim } = await import('../content/problems/defense-claims.js');
hook.deregister();
const catalog = createCatalog(Object.fromEntries(['elements', 'requests', 'events', 'world'].map(name => [name, JSON.parse(fs.readFileSync(new URL(`../catalog/${name}.json`, import.meta.url)))])));
const problem = problemById.get('url-shortener');
const sim = createSim({ catalog, problem });
sim.loadGraph(problem.editorial.designs[0].graph); sim.start(); sim.advance(86400000);
const result = sim.result(), graph = result.graph, context = { problem, graph, result, catalog };
const [cut, saving] = claimsFor({ kind: 'cost' }, problem, graph, catalog, result);
const first = checkClaim(cut, context), originalChecks = structuredClone(first.checks);
assert(first.applied);
assert.equal(globalThis.__claimReplayDays, 2);
checkClaim(saving, context);
assert.equal(globalThis.__claimReplayDays, 2, 'service and bill claims reuse the same measured fleet cut');
first.checks.availability = !first.checks.availability;
const rejected = checkClaim({ ...cut, position: 'fail' }, context);
assert.deepEqual(rejected.checks, originalChecks, 'a returned report cannot alter the cached evidence');
assert.equal(rejected.held, first.held);
assert.equal(rejected.matched, !first.matched, 'the new committed position is checked independently');
assert.equal(globalThis.__claimReplayDays, 2);
const edited = structuredClone(graph);
edited.nodes.find(n => n.id === cut.nodeId).units++;
checkClaim(cut, { ...context, graph: edited });
assert.equal(globalThis.__claimReplayDays, 3, 'a graph edit requires a fresh replay');
edited.nodes.find(n => n.id === cut.nodeId).units++;
checkClaim(cut, { ...context, graph: edited });
assert.equal(globalThis.__claimReplayDays, 4, 'mutating the same graph object also invalidates the evidence');
checkClaim(cut, { ...context, problem: { ...problem, requirements: { ...problem.requirements, peakRps: problem.requirements.peakRps * 2 } } });
assert.equal(globalThis.__claimReplayDays, 5, 'changed arrivals require a fresh replay');
const retry = claimsFor({ kind: 'pool', nodeId: cut.nodeId }, problem, graph, catalog, result).find(c => c.kind === 'retry');
const burst = checkClaim(retry, context);
const other = checkClaim({ ...retry, id: 'another-follow-up', nodeId: 'different-boundary', position: 'fail' }, context);
assert.equal(globalThis.__claimReplayDays, 6, 'the same retry intervention retains its measured noon applicability');
assert.equal(other.applied, burst.applied);
assert.equal(other.held, burst.held);
result.seed = 'another-seed';
checkClaim(cut, context);
assert.equal(globalThis.__claimReplayDays, 7, 'a changed seed requires a fresh replay');
delete globalThis.__claimReplayDays;
console.log('Identical replays reuse evidence; predictions, report edits, graph edits, workloads and seeds stay independent.');
