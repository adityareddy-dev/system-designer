import assert from 'node:assert/strict';
import { page } from '../tools/site-template.mjs';
import { articleData, replaceSeoTags } from '../tools/site-seo.mjs';
const guide = { file: 'guides/example/index.html', title: 'Example', description: 'A guide.' };
assert.equal(articleData(guide).isAccessibleForFree, true);
assert.equal(articleData(guide).hasPart, undefined);
const gated = articleData({ ...guide, gatedSelector: '.guide-members' });
assert.equal(gated.isAccessibleForFree, false);
assert.deepEqual(gated.hasPart, { '@type': 'WebPageElement', isAccessibleForFree: false, cssSelector: '.guide-members' });
const rendered = page(guide.file, { ...guide, crumbs: [['Home', 'index.html']], body: '<div class="guide-members">Member section</div>', data: [gated] });
assert.ok(rendered.includes('"isAccessibleForFree":false,"cssSelector":".guide-members"'));
assert.ok(rendered.includes('"isAccessibleForFree":false,"hasPart"'));
const unrelated = '<script defer src="/consent.js"></script><meta name="theme-color" content="#FFF4E0"><link rel="preload" href="/font.woff2" as="font">';
const html = `<html><head>${unrelated}<title>Old</title><meta name="description" content="Old"></head><body>Keep this</body></html>`;
const changed = replaceSeoTags(html, guide.file, guide, { '@context': 'https://schema.org' });
assert.ok(changed.includes(unrelated));
assert.ok(changed.endsWith('<body>Keep this</body></html>'));
assert.equal(changed.match(/<title>/g).length, 1);
assert.equal(replaceSeoTags(changed, guide.file, guide, { '@context': 'https://schema.org' }), changed);
console.log('PASS structured data: free and gated articles, unrelated head tags preserved, repeatable SEO updates');
