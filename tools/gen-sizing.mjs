// Measures each Hard reference design to connect workload estimates with installed capacity.
import fs from 'node:fs';
import { createCatalog } from '../sim/catalog.js';
import { createSim } from '../sim/engine.js';
import { problems } from '../content/problems/index.js';
const catalog = createCatalog(Object.fromEntries(['elements','requests','events','world'].map(k => [k, JSON.parse(fs.readFileSync(`catalog/${k}.json`, 'utf8'))])));
const sizing = {};
for (const p of problems.filter(p => p.difficulty === 'Hard')) {
  sizing[p.id] = p.editorial.designs.map(d => {
    const sim = createSim({ catalog, problem: p, seed: 'practice' }); sim.loadGraph(d.graph); sim.start(); sim.advance(86400000);
    const result = sim.result();
    return { score: result.score.total, passed: result.passed, cost: result.slo.cost.perMonth,
      rows: result.nodes.filter(n => n.peakRequests > 0 && ['compute','store','cache','queue'].includes(catalog.elementById.get(n.type)?.kind)).map(n => {
        const g = sim.getGraph().nodes.find(g => g.id === n.id), el = catalog.elementById.get(n.type);
        const tier = catalog.world.tiers[g.tier] || catalog.world.tiers.M;
        const factor = el.knobs.includes('tier') ? tier.capacity : 1;
        const headroomUnits = n.effectiveRpsPerUnit > 0 ? Math.ceil(n.peakRequests / (n.effectiveRpsPerUnit * .7)) : null;
        return { id: n.id, type: n.type, installed: g.units, zones: g.zones, tier: g.tier,
          readsPerUnit: Math.round(el.capacity.rps * factor), writesPerUnit: Math.round((el.capacity.writeRps || el.capacity.rps) * factor),
          peakRequests: Math.round(n.peakRequests), activeAtPeak: n.peakUnits, installedAtPeak: n.peakInstalledUnits, peakUtil: n.peakUtil,
          effectivePerUnit: Math.round(n.effectiveRpsPerUnit), headroomUnits,
          installedForHeadroom: headroomUnits == null ? null : Math.ceil(headroomUnits * n.peakInstalledUnits / n.peakUnits) };
      }) };
  });
}
fs.writeFileSync('content/sizing.js', '// Measured reference capacity, generated by tools/gen-sizing.mjs.\nexport default ' + JSON.stringify(sizing) + ';\n');
console.log(`Measured ${Object.keys(sizing).length} Hard problems.`);
