// Finds a "new twist" day for every problem: the same brief and goals, with the events moved and one more event added,
// chosen so the reference design still passes. Writes content/problems/twists.js. Run from the app folder: node tools/gen-twists.mjs [problemId ...]
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const J = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const imp = (f) => import(pathToFileURL(path.resolve(f)).href);
const { createCatalog } = await imp('sim/catalog.js');
const { createSim } = await imp('sim/engine.js');
const { problems } = await imp('content/problems/index.js');
const { twistEvents } = await imp('content/problems/twist-events.js');
const catalog = createCatalog({ elements: J('catalog/elements.json'), requests: J('catalog/requests.json'), events: J('catalog/events.json'), world: J('catalog/world.json') });
const only = new Set(process.argv.slice(2));
const table = {};
const outFile = 'content/problems/twists.js';
if (only.size) { try { Object.assign(table, (await imp(outFile)).default); } catch { /* start fresh */ } }
const passes = (p, events) => {
  const sim = createSim({ catalog, problem: { ...p, events }, seed: 'practice', mode: 'practice' });
  sim.loadGraph(p.editorial.designs[0].graph); sim.start(); sim.advance(86400000);
  return sim.result().passed;
};
for (const p of problems) {
  if (only.size && !only.has(p.id)) continue;
  const used = new Set(p.events.map((e) => e.id));
  const extras = [...(p.eventPool || []).filter((id) => !used.has(id) && catalog.eventById.get(id)), null];
  const h = [...p.id].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7);
  const shifts = h % 2 ? [90, -90, 45, -45] : [-90, 90, -45, 45];
  const ats = ['16:40', '11:20', '04:30'];
  let found = null;
  search: for (const extra of extras) for (const shiftMin of shifts) for (const at of extra ? ats : ['']) {
    const spec = { shiftMin, extra: extra ? { id: extra, at } : null };
    if (passes(p, twistEvents(p, spec))) { found = spec; break search; }
  }
  table[p.id] = found || { shiftMin: 0, extra: null, none: true };
  console.log(p.id, JSON.stringify(table[p.id]));
}
const body = Object.keys(table).sort().map((k) => ` ${JSON.stringify(k)}: ${JSON.stringify(table[k])},`).join('\n');
fs.writeFileSync(outFile, `// Generated by tools/gen-twists.mjs. For each problem: how far its events move, and the one event added, so the reference design still passes. Do not edit by hand.\nexport default {\n${body}\n};\n`);
