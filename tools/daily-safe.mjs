// Measures how strong each daily problem's variant can be while a reference design still passes it, and writes
// compete/daily-safe.js. Run from the app folder: node tools/daily-safe.mjs [--write] [--jobs 4]
import fs from 'node:fs';
import path from 'node:path';
import { fork } from 'node:child_process';
import { pathToFileURL, fileURLToPath } from 'node:url';

const J = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const imp = (f) => import(pathToFileURL(path.resolve(f)).href);
const MAGS = [0.75, 0.9, 1, 1.1, 1.25];
const SHIFTS = [-60, 0, 60];
const AT = ['10:00', '14:30', '19:00'];
// Found by running tests/daily-solvable.mjs over 720 days (other seeds and shifts than the grid above): these pass only
// by a hair, so a different seed tips them over. Problems listed in SKIP stay out of the daily pool.
const SKIP = ['ai-chatbot-serving', 'notification-service', 'stock-order-matching'];
const DROP_EXTRAS = {
  'food-delivery': ['cache-stampede', 'zone-outage', 'dependency-outage'], recommendations: ['bad-deploy'], 'lab-results': ['slow-dependency'],
  'vaccine-signup-surge': ['ddos-attack'], 'ride-hailing-dispatch': ['slow-dependency'],
};

if (process.argv[2] === '--child') {
  const { createCatalog } = await imp('sim/catalog.js');
  const { createSim } = await imp('sim/engine.js');
  const { problems } = await imp('content/problems/index.js');
  const { applyVariant } = await imp('compete/daily.js');
  const catalog = createCatalog({ elements: J('catalog/elements.json'), requests: J('catalog/requests.json'), events: J('catalog/events.json'), world: J('catalog/world.json') });
  const passes = (base, variant, seed) => {
    const prob = applyVariant(base, variant, catalog);
    for (const design of base.editorial?.designs || []) {
      const sim = createSim({ catalog, problem: prob, seed, mode: 'challenge' });
      sim.loadGraph(design.graph);
      sim.start();
      sim.advance(86400000);
      if (sim.result().passed) return true;
    }
    return false;
  };
  // Largest run of magnitudes around 1 that pass at every probed shift (and time of the extra event).
  const range = (base, extraEventId) => {
    const ok = MAGS.map((m) => {
      for (const s of SHIFTS) for (const at of extraEventId ? AT : [null]) {
        if (!passes(base, { shiftMin: s, magnitude: m, extraEventId, extraAt: at }, 'daily-2026-11-03')) return false;
      }
      return true;
    });
    const one = MAGS.indexOf(1);
    if (!ok[one]) return null;
    let lo = one, hi = one;
    while (lo > 0 && ok[lo - 1]) lo--;
    while (hi < MAGS.length - 1 && ok[hi + 1]) hi++;
    return [MAGS[lo], MAGS[hi]];
  };
  process.on('message', (ids) => {
    for (const id of ids) {
      const base = problems.find((p) => p.id === id);
      const out = { id, base: range(base, null), extras: {} };
      for (const e of base.eventPool || []) out.extras[e] = range(base, e);
      process.send(out);
    }
    process.exit(0);
  });
} else {
  const jobs = Number(process.argv[process.argv.indexOf('--jobs') + 1]) || 4;
  const { problems } = await imp('content/problems/index.js');
  // --only a,b measures just those problems and merges them into the existing table
  const onlyAt = process.argv.indexOf('--only');
  const only = onlyAt >= 0 ? new Set(process.argv[onlyAt + 1].split(',')) : null;
  const ids = problems.filter((p) => p.daily && (!only || only.has(p.id))).map((p) => p.id);
  const rows = [];
  let live = 0;
  await new Promise((resolve) => {
    for (let j = 0; j < jobs; j++) {
      const mine = ids.filter((_, i) => i % jobs === j);
      const c = fork(fileURLToPath(import.meta.url), ['--child']);
      live++;
      c.on('message', (m) => { rows.push(m); process.stderr.write('.'); });
      c.on('exit', () => { if (--live === 0) resolve(); });
      c.send(mine);
    }
  });
  rows.sort((a, b) => a.id.localeCompare(b.id));
  const table = {};
  for (const r of rows) {
    const t = { mag: r.base || [1, 1], extras: {} };
    for (const [e, v] of Object.entries(r.extras)) {
      if (!v) continue;
      const lo = Math.max(v[0], t.mag[0]), hi = Math.min(v[1], t.mag[1]);
      if (hi - lo >= 0.15) t.extras[e] = [lo, hi];
    }
    for (const e of DROP_EXTRAS[r.id] || []) delete t.extras[e];
    if (SKIP.includes(r.id)) t.skip = true;
    table[r.id] = t;
  }
  if (only) { const old = (await imp('compete/daily-safe.js')).DAILY_SAFE; for (const k of Object.keys(old)) if (!table[k]) table[k] = old[k]; }
  const sorted = Object.fromEntries(Object.keys(table).sort().map((k) => [k, table[k]]));
  console.error('');
  const src = `// Generated by tools/daily-safe.mjs. For each daily problem: the size range of the day's events (1 = standard) and the\n// extra events that a reference design still passes, so every daily scenario can be passed. Do not edit by hand.\nexport const DAILY_SAFE = ${JSON.stringify(sorted, null, 1)};\n`;
  if (process.argv.includes('--write')) fs.writeFileSync('compete/daily-safe.js', src);
  else console.log(src);
}
